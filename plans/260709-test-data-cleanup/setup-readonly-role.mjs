import pg from "pg";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const { Client } = pg;

// Admin password is read from the project's own .env.local (SUPABASE_DB_PASSWORD)
// rather than hardcoded here, so this script has no standing secret of its own.
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const envLocal = fs.readFileSync(path.join(repoRoot, ".env.local"), "utf8");
const dbPassword = envLocal.match(/^SUPABASE_DB_PASSWORD=(.*)$/m)?.[1]?.trim();
if (!dbPassword) throw new Error("SUPABASE_DB_PASSWORD not found in .env.local");

const ROLE = "cleanup_readonly";
const PASSWORD = crypto.randomBytes(24).toString("base64url");

const client = new Client({
  host: "db.mnoqeluywookswpcykha.supabase.co",
  port: 5432,
  user: "postgres",
  password: dbPassword,
  database: "postgres",
  ssl: { rejectUnauthorized: false },
});

async function main() {
  await client.connect();

  const existing = await client.query(`SELECT 1 FROM pg_roles WHERE rolname = $1;`, [ROLE]);
  if (existing.rowCount > 0) {
    // Role survived from an earlier partial run (dependent grants block DROP
    // ROLE). Reset its password instead -- confirmed live: Supabase's managed
    // `postgres` denies ALTER ROLE ... NOSUPERUSER/etc (attribute changes) but
    // allows ALTER ROLE ... PASSWORD (this is the operation tenants are
    // expected to use for their own created roles).
    await client.query(`ALTER ROLE ${ROLE} PASSWORD '${PASSWORD.replace(/'/g, "''")}';`);
  } else {
    await client.query(`CREATE ROLE ${ROLE} LOGIN PASSWORD '${PASSWORD.replace(/'/g, "''")}';`);
  }
  await client.query(`GRANT CONNECT ON DATABASE postgres TO ${ROLE};`);
  await client.query(`GRANT USAGE ON SCHEMA public TO ${ROLE};`);
  await client.query(`GRANT SELECT ON ALL TABLES IN SCHEMA public TO ${ROLE};`);
  await client.query(
    `ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO ${ROLE};`
  );
  // No explicit ALTER ROLE ... NOSUPERUSER/NOCREATEDB/etc: CREATE ROLE already
  // defaults to none of those attributes unless named, and Supabase's managed
  // `postgres` role denies ALTER ROLE outright ("permission denied to alter
  // role") even though CREATE ROLE/GRANT work fine -- confirmed live.

  const check = await client.query(
    `SELECT rolname, rolsuper, rolcreatedb, rolcreaterole, rolcanlogin FROM pg_roles WHERE rolname = $1;`,
    [ROLE]
  );
  console.log("ROLE_CREATED", JSON.stringify(check.rows[0]));

  const envPath = path.join(path.dirname(fileURLToPath(import.meta.url)), ".env.cleanup.local");
  // No ?sslmode=require: Supabase's cert isn't in the default trust chain and
  // pg treats "require" as "verify-full", which then self-signed-errors.
  // Connect with `ssl: { rejectUnauthorized: false }` in code instead.
  const roURL = `postgresql://${ROLE}:${PASSWORD}@db.mnoqeluywookswpcykha.supabase.co:5432/postgres`;
  fs.writeFileSync(
    envPath,
    [
      "# Read-only Postgres role for the Phase 1 discovery scan (project-mood-studio",
      "# dataset cleanup). Regenerated by setup-readonly-role.mjs -- safe to re-run,",
      "# it only resets this one role's password.",
      `MOOD_CLEANUP_RO_DATABASE_URL=${roURL}`,
      "",
    ].join("\n")
  );
  console.log("Wrote", envPath);

  await client.end();
}

main().catch((err) => {
  console.error("FAILED", err.message);
  process.exit(1);
});
